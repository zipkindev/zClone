#!/usr/bin/env bash
# Insert the rc docs into docs/content/rc.md

set -e

mkdir -p /tmp/zclone/cache_test
mkdir -p /tmp/zclone/rc_mount
export ZCLONE_CONFIG_RCDOCS_TYPE=cache
export ZCLONE_CONFIG_RCDOCS_REMOTE=/tmp/zclone/cache_test
./build/zclone -q --rc mount rcdocs: /tmp/zclone/rc_mount &
sleep 0.5
./build/zclone rc > /tmp/zclone/z.md
fusermount -u -z /tmp/zclone/rc_mount > /dev/null 2>&1 || umount /tmp/zclone/rc_mount

awk '
    BEGIN       {p=1}
    /^<!-- autogenerated start/  {print;system("cat /tmp/zclone/z.md");p=0}
    /^<!-- autogenerated stop/   {p=1}
    p' docs/content/rc.md > /tmp/zclone/rc.md

mv /tmp/zclone/rc.md docs/content/rc.md
rm -rf /tmp/zclone
